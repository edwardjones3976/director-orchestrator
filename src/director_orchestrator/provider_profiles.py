class _StrictLoader(yaml.SafeLoader):
    """SafeLoader that refuses duplicate mapping keys instead of keeping the last."""

    def construct_mapping(self, node: Any, deep: bool = False) -> dict[Any, Any]:
        if not isinstance(node, yaml.MappingNode):
            raise ProviderProfileError("YAML mapping expected")
        seen: set[Any] = set()
        for key_node, _value_node in node.value:
            key = self.construct_object(key_node, deep=deep)
            if key in seen:
                raise ProviderProfileError(
                    f"duplicate YAML mapping key is not allowed: {key!r}"
                )
            seen.add(key)
        return super().construct_mapping(node, deep=deep)


def load_yaml_document(path: str | Path, *, max_bytes: int = MAX_YAML_BYTES) -> JsonObject:
    document_path = Path(path)
    try:
        with document_path.open("rb") as handle:
            raw = handle.read(max_bytes + 1)
    except OSError as exc:
        raise ProviderProfileError(f"cannot read YAML document: {document_path}") from exc
    if len(raw) > max_bytes:
        raise ProviderProfileError(f"YAML document exceeds the {max_bytes}-byte limit")
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise ProviderProfileError(f"{document_path} is not valid UTF-8") from exc
    if not text.isascii():
        raise ProviderProfileError(f"{document_path} must contain ASCII only")
    try:
        value = yaml.load(text, Loader=_StrictLoader)
    except ProviderProfileError:
        raise
    except yaml.YAMLError as exc:
        raise ProviderProfileError(f"{document_path} is not valid YAML") from exc
    if not isinstance(value, dict):
        raise ProviderProfileError(f"{document_path} must contain one YAML mapping")
    return value


@lru_cache(maxsize=1)
def _validators() -> dict[str, Draft202012Validator]:
    schema = load_json_document(SCHEMA_PATH, max_bytes=256_000)
    Draft202012Validator.check_schema(schema)
    schema_id = schema.get("$id")
    if not isinstance(schema_id, str) or not schema_id:
        raise ProviderProfileError("provider profile schema is missing its $id")
    registry: Registry = Registry().with_resource(
        schema_id, DRAFT202012.create_resource(schema)
    )
    return {
        "document": Draft202012Validator(schema, registry=registry),
        PROFILE_DOCUMENT_TYPE: Draft202012Validator(
            {"$ref": f"{schema_id}#/$defs/profileDocument"}, registry=registry
        ),
        CATALOG_DOCUMENT_TYPE: Draft202012Validator(
            {"$ref": f"{schema_id}#/$defs/routeCatalogDocument"}, registry=registry
        ),
    }


def schema_definitions() -> JsonObject:
    schema = load_json_document(SCHEMA_PATH, max_bytes=256_000)
    return dict(schema["$defs"])


def lane_order() -> list[str]:
    return list(schema_definitions()["lane"]["enum"])


def validate_document(document: Mapping[str, Any]) -> None:
    kind = document.get("document_type")
    if kind == PROFILE_DOCUMENT_TYPE:
        has_modes = "execution_modes" in document
        if has_modes != (document.get("provider_id") == "antigravity"):
            raise ProviderProfileError("execution_modes is required only for Antigravity")
    validators = _validators()
    if kind not in validators:
        raise ProviderProfileError(
            f"unknown document_type {kind!r}; expected "
            f"{PROFILE_DOCUMENT_TYPE!r} or {CATALOG_DOCUMENT_TYPE!r}"
        )
    errors = sorted(
        validators[kind].iter_errors(dict(document)), key=lambda item: list(item.path)
    )
    if not errors:
        return
    error = errors[0]
    location = "$" + "".join(
        f"[{part}]" if isinstance(part, int) else f".{part}" for part in error.absolute_path
    )
    raise ProviderProfileError(
        f"{kind} document fails schema at {location} ({error.validator}): {error.message}"
    )


def load_route_catalog(root: Path | None = None) -> JsonObject:
    catalog = load_yaml_document((root or PROFILE_ROOT) / CATALOG_FILENAME)
    validate_document(catalog)
    return catalog


def load_profiles(root: Path | None = None) -> dict[str, JsonObject]:
    profile_root = root or PROFILE_ROOT
    order = lane_order()
    loaded: dict[str, JsonObject] = {}
    for path in sorted(profile_root.glob("*.yaml")):
        if path.name == CATALOG_FILENAME:
            continue
        document = load_yaml_document(path)
        validate_document(document)
        if document.get("document_type") != PROFILE_DOCUMENT_TYPE:
            raise ProviderProfileError(f"{path.name} is not a provider profile")
        if document["provider_id"] != path.stem:
            raise ProviderProfileError(
                f"{path.name} declares provider_id {document['provider_id']!r}"
            )
        loaded[path.stem] = document
    return {lane: loaded[lane] for lane in order if lane in loaded} | {
        lane: doc for lane, doc in loaded.items() if lane not in order
    }


def _route_involves(route: Mapping[str, Any], lane: str) -> bool:
    endpoints = route["endpoints"]
    if route["providers_involved"]:
        return lane in route["providers_involved"]
    return endpoints["from"] == "all_providers" or endpoints["to"] == "all_providers"


def _is_peer_route(route: Mapping[str, Any], lanes: set[str]) -> bool:
    allowed = lanes | {"all_providers"}
    endpoints = route["endpoints"]
    return endpoints["from"] in allowed and endpoints["to"] in allowed


def cross_validate(
    profiles: Mapping[str, Mapping[str, Any]],
    catalog: Mapping[str, Any],
    *,
    root: Path | None = None,
) -> list[str]:
    """Return every consistency problem between the profiles and the catalog."""

    problems: list[str] = []
    repo_root = root or _ROOT
    order = lane_order()
    lanes = set(order)
    if list(catalog["lanes"]) != order:
        problems.append("catalog lanes must equal the schema lane order")
    route_ids = [route["route_id"] for route in catalog["routes"]]
    if len(route_ids) != len(set(route_ids)):
        problems.append("route_id values must be unique")
    routes_by_id = {route["route_id"]: route for route in catalog["routes"]}
    peer_rule = routes_by_id.get(PEER_RULE_ROUTE_ID)
    if peer_rule is None:
        problems.append(f"catalog must define the {PEER_RULE_ROUTE_ID} route")

    for route in catalog["routes"]:
        if (route["status"] == "authorized" and not route["enforced_by"]
                and route["route_id"] != "shared-workflow-skills"):
            problems.append(f"{route['route_id']}: authorized route requires an enforcer")
        for reference in route["charter_basis"]:
            document = repo_root / reference["document"]
            try:
                text = document.read_text(encoding="utf-8")
            except OSError:
                problems.append(f"{route['route_id']}: missing document {reference['document']}")
                continue
            if reference["anchor"] not in text:
                problems.append(
                    f"{route['route_id']}: anchor not found verbatim in "
                    f"{reference['document']}: {reference['anchor']!r}"
                )
        for code_ref in route["enforced_by"]:
            path_part = code_ref.split(":", 1)[0]
            if not (repo_root / path_part).is_file():
                problems.append(f"{route['route_id']}: enforced_by path missing: {path_part}")
        if peer_rule is not None and route is not peer_rule:
            if route["kind"] == "direct" and _is_peer_route(route, lanes):
                problems.append(
                    f"{route['route_id']}: only {PEER_RULE_ROUTE_ID} may describe a "
                    "provider-to-provider endpoint pair"
                )

    for lane, profile in profiles.items():
        identifiers = profile["identifiers"]
        if profile["provider_id"] != lane or identifiers["lane_id"] != lane:
            problems.append(f"{lane}: provider_id and identifiers.lane_id must equal the lane")
        expected_backend = "gemini" if lane == "antigravity" else lane
        if identifiers["backend_identity"] != expected_backend:
            problems.append(f"{lane}: backend_identity must be {expected_backend!r}")
        for transport in profile["transports"]:
            route_id = transport["route_id"]
            if route_id is not None and route_id not in routes_by_id:
                problems.append(f"{lane}: transport {transport['transport_id']} names unknown route {route_id}")
        if peer_rule is not None and lane not in peer_rule["providers_involved"]:
            problems.append(f"{lane}: missing from the {PEER_RULE_ROUTE_ID} route")
        mediated = [
            route
            for route in catalog["routes"]
            if route["kind"] == "mediated"
            and route["status"] == "authorized"
            and _route_involves(route, lane)
        ]
        if not mediated:
            problems.append(f"{lane}: no authorized mediated route reaches this lane")
        for reference in profile["sources"]:
            document = repo_root / reference["document"]
            try:
                text = document.read_text(encoding="utf-8")
            except OSError:
                problems.append(f"{lane}: missing source document {reference['document']}")
                continue
            if reference["anchor"] not in text:
                problems.append(
                    f"{lane}: source anchor not found verbatim in "
                    f"{reference['document']}: {reference['anchor']!r}"
                )

    missing = [lane for lane in order if lane not in profiles]
    if missing:
        problems.append("profiles missing for lanes: " + ", ".join(missing))
    extra = [lane for lane in profiles if lane not in lanes]
    if extra:
        problems.append("profiles for unknown lanes: " + ", ".join(extra))
    return problems


def routes_for(lane: str, catalog: Mapping[str, Any]) -> list[JsonObject]:
    return [dict(route) for route in catalog["routes"] if _route_involves(route, lane)]


def peer_status(
    lane: str, other: str, catalog: Mapping[str, Any]
) -> tuple[str, list[str], list[str]]:
    """Return (status, direct_route_ids, mediated_route_ids) for an ordered pair."""

    if lane == other:
        raise ValueError("peer_status requires two different lanes")
    lanes = set(catalog["lanes"])
    direct: list[str] = []
    statuses: list[str] = []
    mediated: list[str] = []
    for route in catalog["routes"]:
        involves_both = _route_involves(route, lane) and _route_involves(route, other)
        if not involves_both:
            continue
        if route["kind"] == "direct" and _is_peer_route(route, lanes):
            direct.append(route["route_id"])
            statuses.append(route["status"])
        elif route["kind"] == "mediated" and route["status"] == "authorized":
            mediated.append(route["route_id"])
    if "authorized" in statuses:
        status = "authorized"
    elif "proposed" in statuses:
        status = "proposed"
    else:
        status = "prohibited"
    return status, direct, mediated



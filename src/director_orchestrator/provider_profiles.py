def _cell(value: Any) -> str:
    if value is None:
        return "-"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (list, tuple)):
        if not value:
            return "-"
        return "; ".join(_cell(item) for item in value)
    text = str(value).replace("\r", " ").replace("\n", " ").replace("|", "\\|")
    return text


def _code(value: Any) -> str:
    if value is None:
        return "-"
    if isinstance(value, (list, tuple)):
        if not value:
            return "-"
        return ", ".join(_code(item) for item in value)
    return f"`{_cell(value)}`"


def _table(headers: list[str], rows: list[list[Any]]) -> list[str]:
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    for row in rows:
        lines.append("| " + " | ".join(_cell(item) for item in row) + " |")
    return lines


def _bullets(items: list[Any] | str) -> list[str]:
    if isinstance(items, str):
        items = [items]
    if not items:
        return ["- (none)"]
    return [f"- {_cell(item)}" for item in items]


def _kv_table(pairs: list[tuple[str, Any]]) -> list[str]:
    return _table(["Field", "Value"], [[key, value] for key, value in pairs])


def _require_ascii(text: str, *, label: str) -> str:
    if not text.isascii():
        raise ProviderProfileError(f"{label} must render as ASCII only")
    if "\r" in text:
        raise ProviderProfileError(f"{label} must use LF line endings only")
    return text


def _finish(lines: list[str], *, label: str) -> str:
    text = "\n".join(lines).rstrip("\n") + "\n"
    return _require_ascii(text, label=label)



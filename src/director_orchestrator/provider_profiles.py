@dataclass(frozen=True)
class TagIdentity:
    contributor: str
    system: str
    at: datetime

    def __post_init__(self) -> None:
        if self.at.tzinfo is None or self.at.utcoffset() is None:
            raise ValueError("contribution tag timestamps must be timezone-aware")

    def tag(self, boundary: str) -> str:
        return render_contribution_tag(
            self.contributor, self.system, boundary, at=self.at  # type: ignore[arg-type]
        )

    @property
    def key(self) -> tuple[str, str, str, str]:
        moment = self.at.astimezone(timezone.utc)
        return (
            self.contributor.strip(),
            self.system.strip(),
            f"{moment:%Y-%m-%d}",
            f"{moment:%H:%M}",
        )



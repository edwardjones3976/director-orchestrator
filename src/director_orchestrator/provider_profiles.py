def _normalize_newlines(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n")


def strip_contribution_tag_lines(text: str) -> str:
    lines = _normalize_newlines(text).split("\n")
    kept = [line for line in lines if parse_contribution_tag(line) is None]
    return "\n".join(kept).strip("\n") + "\n"


def _tag_comment(tag: str) -> str:
    return f"<!-- {tag} -->"


def compose_tagged_document(
    body: str, existing: str | None, identity: TagIdentity
) -> str:
    """Wrap a rendered body in a fresh outer tag pair, preserving inner pairs.

    Leading BEGIN lines and trailing END lines already present in ``existing``
    stay inside the new pair. When ``identity`` already forms the outermost
    pair, no second copy is added and only the body is replaced.
    """

    leading: list[str] = []
    trailing: list[str] = []
    if existing:
        lines = _normalize_newlines(existing).split("\n")
        index = 0
        while index < len(lines):
            line = lines[index]
            if not line.strip():
                index += 1
                continue
            tag = parse_contribution_tag(line)
            if tag is None or tag.boundary != "BEGIN":
                break
            leading.append(line)
            index += 1
        index = len(lines) - 1
        while index >= 0:
            line = lines[index]
            if not line.strip():
                index -= 1
                continue
            tag = parse_contribution_tag(line)
            if tag is None or tag.boundary != "END":
                break
            trailing.insert(0, line)
            index -= 1
    outer_begin = parse_contribution_tag(leading[0]) if leading else None
    outer_end = parse_contribution_tag(trailing[-1]) if trailing else None
    already_outer = (
        outer_begin is not None
        and outer_end is not None
        and (outer_begin.contributor, outer_begin.system, outer_begin.date, outer_begin.time)
        == identity.key
        and (outer_end.contributor, outer_end.system, outer_end.date, outer_end.time)
        == identity.key
    )
    begin_lines = list(leading)
    end_lines = list(trailing)
    if not already_outer:
        begin_lines = [_tag_comment(identity.tag("BEGIN"))] + begin_lines
        end_lines = end_lines + [_tag_comment(identity.tag("END"))]
    content = body.strip("\n")
    return "\n".join(begin_lines + [""] + [content] + [""] + end_lines) + "\n"


def planned_outputs(
    identity: TagIdentity | None, *, root: Path | None = None
) -> dict[Path, str]:
    profile_root = root or PROFILE_ROOT
    profiles = load_profiles(profile_root)
    catalog = load_route_catalog(profile_root)
    problems = cross_validate(profiles, catalog)
    if problems:
        raise ProviderProfileError("; ".join(problems))
    outputs: dict[Path, str] = {}
    for lane, profile in profiles.items():
        outputs[profile_root / f"{lane}{SHEET_SUFFIX}"] = render_profile_markdown(profile, catalog)
    outputs[profile_root / INDEX_FILENAME] = render_index_markdown(profiles, catalog)
    if EXAMPLE_PROVIDER in profiles:
        outputs[EXAMPLE_PATH] = render_example_json(profiles[EXAMPLE_PROVIDER])
    if identity is None:
        return outputs
    tagged: dict[Path, str] = {}
    for path, body in outputs.items():
        if path.suffix != ".md":
            tagged[path] = body
            continue
        existing = path.read_text(encoding="utf-8") if path.exists() else None
        tagged[path] = compose_tagged_document(body, existing, identity)
    return tagged


def check_outputs(*, root: Path | None = None) -> list[str]:
    """Return every stale, missing, or mistagged rendered output."""

    problems: list[str] = []
    for path, body in planned_outputs(None, root=root).items():
        if not path.exists():
            problems.append(f"missing rendered output: {path.name}")
            continue
        current = path.read_text(encoding="utf-8")
        if path.suffix == ".md":
            if strip_contribution_tag_lines(current) != strip_contribution_tag_lines(body):
                problems.append(f"stale rendered output: {path.name}")
            relative = path.relative_to(_ROOT).as_posix()
            problems.extend(
                f"{path.name}: {issue}"
                for issue in validate_inline_contribution_tags(relative, current)
            )
        elif _normalize_newlines(current) != body:
            problems.append(f"stale rendered output: {path.name}")
    return problems


def write_outputs(identity: TagIdentity, *, root: Path | None = None) -> list[Path]:
    written: list[Path] = []
    for path, text in planned_outputs(identity, root=root).items():
        _require_ascii(text, label=path.name)
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        written.append(path)
    return written

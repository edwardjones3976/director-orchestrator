    def primary_quiescence_metrics(self) -> PrimaryQuiescenceMetrics:
        """Return exact unresolved-work counts for a fenced rollback decision."""

        schema = self._schema
        with self._pool.connection() as connection:
            row = self._one_row(
                connection,
                f"""
                SELECT
                    (SELECT count(*)
                     FROM {schema}.director_primary_effect_reservation reservation
                     LEFT JOIN {schema}.director_primary_terminal_evidence terminal
                       ON terminal.claim_key = reservation.claim_key
                     WHERE terminal.claim_key IS NULL) AS active_provider_dispatch_count,
                    (SELECT count(*)
                     FROM {schema}.director_primary_parallel_assignment
                     WHERE status IN ('PENDING', 'ACTIVE', 'AMBIGUOUS'))
                        AS active_assignment_count,
                    (SELECT count(*)
                     FROM {schema}.director_primary_task_writer
                     WHERE lease_expires_at > now()) AS live_writer_claim_count,
                    (SELECT count(DISTINCT reconciliation.claim_key)
                     FROM {schema}.director_primary_reconciliation_event reconciliation
                     LEFT JOIN {schema}.director_primary_terminal_evidence terminal
                       ON terminal.claim_key = reconciliation.claim_key
                     WHERE terminal.claim_key IS NULL)
                        AS unresolved_reconciliation_count,
                    (SELECT count(*)
                     FROM {schema}.director_primary_claim claim
                     LEFT JOIN {schema}.director_primary_terminal_evidence terminal
                       ON terminal.claim_key = claim.claim_key
                     WHERE terminal.claim_key IS NULL) AS unsettled_claim_count
                """,
                {},
                missing="primary quiescence metrics did not resolve",
            )
        return PrimaryQuiescenceMetrics(
            active_provider_dispatch_count=int(row["active_provider_dispatch_count"]),
            active_assignment_count=int(row["active_assignment_count"]),
            live_writer_claim_count=int(row["live_writer_claim_count"]),
            unresolved_reconciliation_count=int(row["unresolved_reconciliation_count"]),
            unsettled_claim_count=int(row["unsettled_claim_count"]),
        )

    def record_completion_evidence(
        self,
        *,
        task_id: str,
        candidate_sha: str,
        provider_result_digest: str,
        evidence: "CompletionEvidence",
        owner_token: str,
        fencing_generation: int,
    ) -> PrimaryCompletionEvidenceArtifact:
        """Persist one immutable independently validated completion bundle."""

        _require_id(task_id, "task_id")
        _require_id(owner_token, "owner_token")
        _require_digest(provider_result_digest, "provider_result_digest")
        if re.fullmatch(r"[0-9a-f]{40}", candidate_sha) is None:
            raise PostgresControlPlaneError("candidate_sha must be an exact lowercase SHA")
        generation = _require_generation(fencing_generation, "fencing_generation", minimum=1)
        verifier = self._require_completion_authority_verifier()
        (
            ledger_json,
            results_json,
            authorities_json,
            ledger_digest,
            evidence_digest,
        ) = (
            _completion_evidence_payload(
                evidence, task_id=task_id, candidate_sha=candidate_sha,
                provider_result_digest=provider_result_digest, verifier=verifier,
            )
        )
        parameters = {
            "task_id": task_id, "candidate_sha": candidate_sha,
            "command_id": evidence.command_id,
            "provider_result_digest": provider_result_digest,
            "ledger_digest": ledger_digest, "evidence_digest": evidence_digest,
            "canonical_ledger": ledger_json, "canonical_results": results_json,
            "canonical_authorities": authorities_json,
            "ci_gate_id": evidence.ci_gate_id,
            "security_gate_id": evidence.security_gate_id,
            "owner_token": owner_token, "generation": generation,
        }
        columns = (
            "task_id, command_id, candidate_sha, provider_result_digest, ledger_digest, "
            "evidence_digest, canonical_ledger, canonical_results, "
            "canonical_authorities, ci_gate_id, "
            "security_gate_id, writer_fencing_generation"
        )
        with self._pool.connection() as connection:
            with connection.transaction():
                self._optional_row(
                    connection, "SELECT pg_advisory_xact_lock(%(key)s)",
                    {"key": _advisory_key("completion-evidence", self._schema, task_id)},
                )
                writer = self._optional_row(
                    connection,
                    f"""SELECT task_id FROM {self._schema}.director_primary_task_writer
                        WHERE task_id=%(task_id)s AND engine_owner='langgraph'
                          AND owner_token=%(owner_token)s
                          AND fencing_generation=%(generation)s
                          AND lease_expires_at > now() FOR UPDATE""",
                    parameters,
                )
                if writer is None:
                    raise PostgresControlPlaneError(
                        "completion evidence refused; writer authority is stale or expired"
                    )
                existing = self._optional_row(
                    connection,
                    f"SELECT {columns} FROM {self._schema}.director_primary_completion_evidence WHERE task_id=%(task_id)s",
                    parameters,
                )
                if existing is not None:
                    artifact = _completion_evidence_artifact_from_row(existing, verifier=verifier)
                    if artifact.evidence_digest != evidence_digest:
                        raise PostgresControlPlaneError(
                            "completion evidence identity was replayed with different content"
                        )
                    return artifact
                row = self._optional_row(
                    connection,
                    f"""INSERT INTO {self._schema}.director_primary_completion_evidence
                        ({columns})
                        SELECT writer.task_id, %(command_id)s, %(candidate_sha)s, %(provider_result_digest)s,
                               %(ledger_digest)s, %(evidence_digest)s, %(canonical_ledger)s,
                               %(canonical_results)s, %(canonical_authorities)s,
                               %(ci_gate_id)s, %(security_gate_id)s,
                               writer.fencing_generation
                        FROM {self._schema}.director_primary_task_writer writer
                        WHERE writer.task_id=%(task_id)s AND writer.engine_owner='langgraph'
                          AND writer.owner_token=%(owner_token)s
                          AND writer.fencing_generation=%(generation)s
                          AND writer.lease_expires_at > now()
                        ON CONFLICT (task_id) DO NOTHING RETURNING {columns}""",
                    parameters,
                )
                if row is None:
                    raise PostgresControlPlaneError(
                        "completion evidence insert lost its immutable identity race"
                    )
        return _completion_evidence_artifact_from_row(row, verifier=verifier)


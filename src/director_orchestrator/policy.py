def _inflections(base: str) -> set[str]:
    stem = base[:-1] if base.endswith("e") else base
    forms = {base, base + "s", base + "es", base + "ed", base + "d", stem + "ing",
             stem + "ed", base + base[-1] + "ed", base + base[-1] + "ing"}
    if base.endswith("y"):
        forms |= {base[:-1] + "ies", base[:-1] + "ied"}
    return forms


